CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference        VARCHAR(16)  NOT NULL,
    access_token     VARCHAR(64)  NOT NULL,
    event_id         BIGINT       NOT NULL REFERENCES events (id),
    status           VARCHAR(20)  NOT NULL,
    buyer_name       VARCHAR(120),
    buyer_email      VARCHAR(255),
    subtotal_cents   BIGINT       NOT NULL DEFAULT 0,
    discount_cents   BIGINT       NOT NULL DEFAULT 0,
    total_cents      BIGINT       NOT NULL DEFAULT 0,
    hold_expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    paid_at          TIMESTAMP WITH TIME ZONE,
    cancelled_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_orders_reference UNIQUE (reference),
    CONSTRAINT uq_orders_access_token UNIQUE (access_token)
);

CREATE INDEX idx_orders_event_status ON orders (event_id, status);

CREATE TABLE order_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          BIGINT  NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    tier_id           BIGINT  NOT NULL REFERENCES ticket_tiers (id),
    quantity          INTEGER NOT NULL,
    unit_price_cents  BIGINT  NOT NULL
);

CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_tier ON order_items (tier_id);
