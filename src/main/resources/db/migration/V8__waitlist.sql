CREATE TABLE waitlist_entries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        BIGINT       NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    tier_id         BIGINT       NOT NULL REFERENCES ticket_tiers (id) ON DELETE CASCADE,
    name            VARCHAR(120) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    quantity        INTEGER      NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    offered_at      TIMESTAMP WITH TIME ZONE,
    offer_order_id  BIGINT REFERENCES orders (id),
    CONSTRAINT ck_waitlist_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_waitlist_tier_status ON waitlist_entries (tier_id, status, created_at);
CREATE INDEX idx_waitlist_offer_order ON waitlist_entries (offer_order_id);
